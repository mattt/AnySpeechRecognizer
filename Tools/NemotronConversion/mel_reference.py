"""Write NeMo's Nemotron mel features for a synthetic signal as a Swift test fixture.

The Swift test `NemotronMelFrontendTests` generates the same signal as
`Tools/ParakeetConversion/mel_reference.py` and compares its features with these values.
Run from this directory:

    uv run python mel_reference.py ../../Tests/AnySpeechRecognizerTests/Nemotron/NemotronMelReference.swift
    xcrun swift-format format -i ../../Tests/AnySpeechRecognizerTests/Nemotron/NemotronMelReference.swift
"""

from __future__ import annotations

import math
import sys
from importlib import metadata
from pathlib import Path

import numpy as np

import nemotron as nt

SAMPLE_COUNT = 16_517
BINS = tuple(range(0, nt.MEL_BINS, 8))


def signal() -> np.ndarray:
    """Tones with a slow envelope and noise from a 32-bit linear congruential generator."""
    state = 1
    values = np.zeros(SAMPLE_COUNT, dtype=np.float32)
    for index in range(SAMPLE_COUNT):
        state = (state * 1_664_525 + 1_013_904_223) % (1 << 32)
        noise = (state >> 8) / 16_777_216 - 0.5
        time = index / 16_000
        envelope = 0.5 + 0.5 * math.sin(2 * math.pi * 1.5 * time)
        voiced = (
            math.sin(2 * math.pi * 220 * time)
            + 0.5 * math.sin(2 * math.pi * 1_300 * time)
            + 0.25 * math.sin(2 * math.pi * 3_100 * time)
        )
        values[index] = 0.2 * envelope * voiced + 0.02 * noise
    return values


def main() -> None:
    model, _ = nt.load_model(nt.DEFAULT_CACHE_DIR)
    mel = nt.nemo_mel(model, signal())
    count = mel.shape[1]
    # The first frames, a middle frame, and the last frames, which read zeros after the audio.
    frames = sorted({0, 1, 2, count // 2, count - 3, count - 2, count - 1})
    lines = [
        f"// Generated by Tools/NemotronConversion/mel_reference.py with NeMo {metadata.version('nemo_toolkit')}",
        f"// and {nt.REPOSITORY} at {nt.REVISION[:7]}. Do not edit.",
        "",
        "enum NemotronMelReference {",
        f"    static let sampleCount = {SAMPLE_COUNT}",
        f"    static let frameCount = {count}",
        f"    static let bins = [{', '.join(map(str, BINS))}]",
        f"    static let frames = [{', '.join(map(str, frames))}]",
        "    /// `values[frame index][bin index]`, for `frames` and `bins`.",
        "    static let values: [[Float]] = [",
    ]
    for frame in frames:
        lines.append(f"        [{', '.join(f'{float(mel[b, frame]):.6g}' for b in BINS)}],")
    lines += ["    ]", "}"]
    # NeMo logs to standard output, so the fixture goes to a file.
    Path(sys.argv[1]).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
