"""Write the Qwen3-ASR feature extractor's log-mel features for a synthetic signal as a Swift test fixture.

The Swift test `QwenMelFrontendTests` generates the same signal and compares its features
with these values. Run from this directory:

    uv run python mel_reference.py ../../Tests/AnySpeechRecognizerTests/Qwen/QwenMelReference.swift
    xcrun swift-format format -i ../../Tests/AnySpeechRecognizerTests/Qwen/QwenMelReference.swift
"""

from __future__ import annotations

import math
import sys
from importlib import metadata
from pathlib import Path

import numpy as np

import qwen

# A length that is not a multiple of the hop, and one shorter than the 0.5-second minimum,
# which the extractor pads with zeros.
CASES = (("long", 16_517), ("short", 5_000))
BINS = tuple(range(0, qwen.MEL_BINS, 8))


def signal(count: int) -> np.ndarray:
    """Tones with a slow envelope and noise from a 32-bit linear congruential generator."""
    state = 1
    values = np.zeros(count, dtype=np.float32)
    for index in range(count):
        state = (state * 1_664_525 + 1_013_904_223) % (1 << 32)
        noise = (state >> 8) / 16_777_216 - 0.5
        time = index / 16_000
        envelope = 0.5 + 0.5 * math.sin(2 * math.pi * 1.5 * time)
        voiced = (
            math.sin(2 * math.pi * 220 * time)
            + 0.5 * math.sin(2 * math.pi * 1_300 * time)
            + 0.25 * math.sin(2 * math.pi * 3_100 * time)
        )
        values[index] = 0.2 * envelope * voiced + 0.02 * noise
    return values


def main() -> None:
    from transformers import AutoProcessor

    variant = qwen.VARIANTS["0.6b"]
    processor = AutoProcessor.from_pretrained(str(qwen.snapshot(variant, qwen.DEFAULT_CACHE_DIR)))
    extractor = processor.feature_extractor
    lines = [
        f"// Generated by Tools/QwenConversion/mel_reference.py with transformers {metadata.version('transformers')}",
        f"// and {variant.repo} at {variant.revision[:7]}. Do not edit.",
        "",
        "enum QwenMelReference {",
        f"    static let bins = [{', '.join(map(str, BINS))}]",
        "",
        "    struct Case {",
        "        var sampleCount: Int",
        "        var frameCount: Int",
        "        var frames: [Int]",
        "        /// `values[frame index][bin index]`, for `frames` and `bins`.",
        "        var values: [[Float]]",
        "    }",
        "",
    ]
    for name, count in CASES:
        # The processor's settings: no padding beyond the audio, then whole 100-frame chunks.
        out = extractor(
            signal(count),
            sampling_rate=qwen.SAMPLE_RATE,
            padding=True,
            truncation=False,
            return_attention_mask=True,
            n_window=50,
        )
        valid = int(out["attention_mask"].sum())
        mel = out["input_features"][0].numpy()
        frames = sorted({0, 1, 2, valid // 2, valid - 2, valid - 1})
        values = ",\n".join("            [" + ", ".join(f"{float(mel[b, f]):.6g}" for b in BINS) + "]" for f in frames)
        lines += [
            f"    static let {name} = Case(",
            f"        sampleCount: {count}, frameCount: {valid},",
            f"        frames: [{', '.join(map(str, frames))}],",
            "        values: [",
            values,
            "        ])",
            "",
        ]
    lines.append("}")
    destination = Path(sys.argv[1])
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n")
    print(f"Wrote {destination}")


if __name__ == "__main__":
    main()
