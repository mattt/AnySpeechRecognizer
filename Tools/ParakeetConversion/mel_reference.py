"""Write NeMo's Parakeet mel features for a synthetic signal as a Swift test fixture.

The Swift test `ParakeetMelFrontendTests` generates the same signal and compares its
features with these values. Run from this directory:

    uv run python mel_reference.py ../../Tests/AnySpeechRecognizerTests/Parakeet/ParakeetMelReference.swift
    xcrun swift-format format -i ../../Tests/AnySpeechRecognizerTests/Parakeet/ParakeetMelReference.swift
"""

from __future__ import annotations

import math
import sys
from importlib import metadata
from pathlib import Path

import numpy as np

import parakeet as pk

SAMPLE_COUNT = 16_517
WINDOW_SAMPLES = 32_000
# The recognizer rounds the valid samples up to a whole encoder frame; the second case
# ends the valid samples with the audio.
CASES = (("roundedUp", 17_920), ("exact", SAMPLE_COUNT))
BINS = tuple(range(0, pk.MEL_BINS, 8))


def signal() -> np.ndarray:
    """Tones with a slow envelope and noise from a 32-bit linear congruential generator."""
    state = 1
    values = np.zeros(SAMPLE_COUNT, dtype=np.float32)
    for index in range(SAMPLE_COUNT):
        state = (state * 1_664_525 + 1_013_904_223) % (1 << 32)
        noise = (state >> 8) / 16_777_216 - 0.5
        time = index / 16_000
        envelope = 0.5 + 0.5 * math.sin(2 * math.pi * 1.5 * time)
        voiced = (
            math.sin(2 * math.pi * 220 * time)
            + 0.5 * math.sin(2 * math.pi * 1_300 * time)
            + 0.25 * math.sin(2 * math.pi * 3_100 * time)
        )
        values[index] = 0.2 * envelope * voiced + 0.02 * noise
    return values


def main() -> None:
    model, _, _ = pk.load_model(pk.VARIANTS["v3"], pk.DEFAULT_CACHE_DIR)
    window = np.zeros(WINDOW_SAMPLES, dtype=np.float32)
    window[:SAMPLE_COUNT] = signal()
    mel_frames = WINDOW_SAMPLES // pk.MEL_HOP_SAMPLES + 1
    lines = [
        f"// Generated by Tools/ParakeetConversion/mel_reference.py with NeMo {metadata.version('nemo_toolkit')}",
        f"// and {pk.NVIDIA_V3.repo} at {pk.NVIDIA_V3.revision[:7]}. Do not edit.",
        "",
        "enum ParakeetMelReference {",
        f"    static let sampleCount = {SAMPLE_COUNT}",
        f"    static let windowSamples = {WINDOW_SAMPLES}",
        f"    static let bins = [{', '.join(map(str, BINS))}]",
        "",
        "    struct Case {",
        "        var validSampleCount: Int",
        "        var validFrameCount: Int",
        "        var frames: [Int]",
        "        /// `values[frame index][bin index]`, for `frames` and `bins`.",
        "        var values: [[Float]]",
        "    }",
        "",
    ]
    for name, valid in CASES:
        mel, length = pk.nemo_mel(model, window, valid, mel_frames=mel_frames)
        count = int(length[0])
        if np.any(mel[0, :, count:] != 0):
            raise ValueError("NeMo features after the valid frames are not zero")
        # The first frames, a middle frame, the last frames that read audio, and the last frames.
        audio_end = SAMPLE_COUNT // pk.MEL_HOP_SAMPLES
        frames = sorted({0, 1, 2, count // 2, audio_end - 2, audio_end - 1, count - 2, count - 1})
        lines += [
            f"    static let {name} = Case(",
            f"        validSampleCount: {valid}, validFrameCount: {count},",
            f"        frames: [{', '.join(map(str, frames))}],",
            "        values: [",
        ]
        for frame in frames:
            values = ", ".join(f"{float(mel[0, b, frame]):.6g}" for b in BINS)
            lines.append(f"            [{values}],")
        lines += ["        ])", ""]
    lines[-1] = "}"
    # NeMo logs to standard output, so the fixture goes to a file.
    Path(sys.argv[1]).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
